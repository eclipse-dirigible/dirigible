package org.eclipse.dirigible.components.terminal.endpoint;

import java.nio.charset.StandardCharsets;
import java.security.SecureRandom;
import java.util.Base64;

/**
 * The credential the terminal backend (ttyd) is started with, generated by the platform instance
 * that starts it. The terminal websocket presents it when it connects to the backend.
 */
final class TtydCredential {

    private static final String USER = "dirigible";
    private static final int PASSWORD_BYTES = 32;

    private final String credential;

    private TtydCredential(String credential) {
        this.credential = credential;
    }

    /**
     * Generates a credential with a random password.
     *
     * @return the credential
     */
    static TtydCredential generate() {
        byte[] password = new byte[PASSWORD_BYTES];
        new SecureRandom().nextBytes(password);
        return new TtydCredential(USER + ":" + Base64.getUrlEncoder()
                                                     .withoutPadding()
                                                     .encodeToString(password));
    }

    /**
     * The credential in the {@code user:password} form ttyd's {@code --credential} option takes.
     *
     * @return the credential
     */
    String credential() {
        return credential;
    }

    /**
     * The token ttyd checks: in the Basic authorization header of the websocket handshake and as the
     * {@code AuthToken} of the client's first message.
     *
     * @return the Base64 form of the credential
     */
    String token() {
        return Base64.getEncoder()
                     .encodeToString(credential.getBytes(StandardCharsets.UTF_8));
    }
}
