/**
 * Prepares a model and its parameters for one template.
 *
 * <p>
 * A template descriptor declares only <em>what</em> to render; the preparation each template needs
 * before its sources are rendered - which node of the model file to generate from, and the derived
 * parameters its sources reference - is per-template knowledge, and this is where it lives.
 *
 * <p>
 * A template the pipeline does not know is refused by name rather than generated incompletely.
 */
final class ModelTemplateAdapters {

    /** The default brand icon of a generated application. */
    private static final String DEFAULT_APP_ICON = "blocks";

    /** The default data language of a generated application. */
    private static final String DEFAULT_APP_LANGUAGE = "en";

    /**
     * Not instantiable.
     */
    private ModelTemplateAdapters() {}

    /**
     * A model prepared for generation.
     *
     * @param model the node to generate from
     * @param entityShaped whether the node is an entity model, which selects the entity pipeline
     */
    record PreparedModel(Map<String, Object> model, boolean entityShaped) {
    }

    /** The template rendering a standalone report. */
    private static final String REPORT_FILE_TEMPLATE = "template-application-ui-harmonia-java/template/template-report-file.js";

    /** The preparation of each supported template, keyed by its module path. */
    private static final Map<String, Adapter> ADAPTERS = Map.of(//
            "template-application-schema/template/template.js", ModelTemplateAdapters::entityModel, //
            "template-application-dao-java/template/template.js", ModelTemplateAdapters::javaEntityModel, //
            "template-application-rest-java/template/template.js", ModelTemplateAdapters::javaEntityModel, //
            "template-application-ui-harmonia-java/template/template.js", ModelTemplateAdapters::harmoniaApplication, //
            "template-application-events-java/template/template.js", ModelTemplateAdapters::glue, //
            REPORT_FILE_TEMPLATE, ModelTemplateAdapters::report, //
            "template-form-builder-harmonia/template/template.js", (modelText, parameters) -> form(modelText), //
            "template-mapping-javascript/template/template.js", (modelText, parameters) -> mapping(modelText), //
            "template-mapping-java/template/template.js", ModelTemplateAdapters::javaMapping);

    /**
     * Prepares a model for a template.
     *
     * @param templateId the template's module path, as the request names it
     * @param modelText the raw model file
     * @param parameters the generation parameters, mutated with the template's derived parameters
     * @return the prepared model
     * @throws IllegalArgumentException when the template has no Java preparation
     */
    static PreparedModel prepare(String templateId, String modelText, Map<String, Object> parameters) {
        Adapter adapter = ADAPTERS.get(templateId);
        if (adapter == null) {
            throw new IllegalArgumentException("Template [" + templateId + "] is not supported by the Java model-generation pipeline.");
        }
        return adapter.prepare(modelText, parameters);
    }

    /**
     * Tests whether a template can be generated by the Java pipeline.
     *
     * @param templateId the template's module path
     * @return true when it is supported
     */
    static boolean supports(String templateId) {
        return ADAPTERS.containsKey(templateId);
    }

    /**
     * The paths, relative to the generation folder, where an earlier version of a template wrote output
     * it now writes elsewhere - for a regeneration to remove, so the old copy does not outlive the
     * move.
     *
     * <p>
     * A standalone report's page went to the case-preserved {@code gen/<Report>/reports/<Report>/},
     * beside its Java in the sanitized {@code gen/<report>/} (#7889). On a case-sensitive filesystem
     * those are two folders, and the reports store listed the report twice.
     *
     * @param templateId the template's module path
     * @param parameters the generation parameters, as {@link #prepare} left them
     * @return the retired paths; empty for a template that moved nothing
     */
    static List<String> retiredOutputs(String templateId, Map<String, Object> parameters) {
        String genFolder = str(parameters, "genFolderName");
        if (!REPORT_FILE_TEMPLATE.equals(templateId) || genFolder.equals(str(parameters, "javaGenFolderName"))) {
            return List.of();
        }
        return List.of(genFolder + "/reports/" + str(parameters, "name"));
    }

    /**
     * The preparation of one template.
     */
    @FunctionalInterface
    private interface Adapter {

        /**
         * Prepares a model.
         *
         * @param modelText the raw model file
         * @param parameters the generation parameters
         * @return the prepared model
         */
        PreparedModel prepare(String modelText, Map<String, Object> parameters);
    }

    /**
     * Prepares a plain entity model - the schema, DAO and REST layers.
     *
     * @param modelText the raw model file
     * @param parameters the generation parameters
     * @return the prepared model
     */
    private static PreparedModel entityModel(String modelText, Map<String, Object> parameters) {
        Map<String, Object> model = entityRoot(modelText);
        ModelParameterProcessor.process(model, parameters);
        return new PreparedModel(model, true);
    }

    /**
     * Prepares an entity model for the Java layers, which evaluate its calculated-field formulas.
     *
     * @param modelText the raw model file
     * @param parameters the generation parameters
     * @return the prepared model
     */
    private static PreparedModel javaEntityModel(String modelText, Map<String, Object> parameters) {
        PreparedModel prepared = entityModel(modelText, parameters);
        CalculatedFormulas.resolve(asMaps(prepared.model()
                                                  .get("entities")));
        return prepared;
    }

    /**
     * Prepares the full application stack, whose UI needs the application's own caption, icon,
     * languages and dashboard widgets.
     *
     * @param modelText the raw model file
     * @param parameters the generation parameters
     * @return the prepared model
     */
    private static PreparedModel harmoniaApplication(String modelText, Map<String, Object> parameters) {
        Map<String, Object> model = entityRoot(modelText);
        parameters.put("javaRuntime", Boolean.TRUE);
        ModelParameterProcessor.process(model, parameters);
        CalculatedFormulas.resolve(asMaps(model.get("entities")));
        // The shell's title and sidebar header prefer the model's own title and description over the
        // bare project name.
        parameters.put("appTitle", blankToNull(str(model, "title")) != null ? model.get("title") : parameters.get("projectName"));
        // The administration perspective descriptor is a JSON document, so the title is written into a JSON
        // string.
        parameters.put("appTitleJson", JsonLiterals.escape(String.valueOf(parameters.get("appTitle"))));
        parameters.put("appDescription", strOr(model, "description", ""));
        // An explicit generate-time icon wins over the model's, which wins over a neutral default.
        String appIcon = blankToNull(str(parameters, "appIcon"));
        if (appIcon == null) {
            appIcon = blankToNull(str(model, "icon"));
        }
        parameters.put("appIcon", appIcon == null ? DEFAULT_APP_ICON : appIcon);
        // The data languages the application offers, rendered into its configuration as a JSON array.
        List<Object> languages = ModelValues.asList(model.get("languages"));
        parameters.put("appLanguages",
                JavaScriptJson.compact(languages.isEmpty() ? List.of(DEFAULT_APP_LANGUAGE) : new ArrayList<>(languages)));
        // Whether the application has data to translate at all - a multilingual entity. The shell's
        // translation check holds the declared data languages against the platform's only then, so a
        // fully translated application without such data is not reported as untranslated (#8137).
        parameters.put("appTranslatableData", ModelValues.asMaps(model.get("entities"))
                                                         .stream()
                                                         .anyMatch(entity -> ModelValues.isTrue(entity, "multilingual")));
        parameters.put("customWidgets", model.get("widgets") == null ? new ArrayList<>() : model.get("widgets"));
        // Country-scoped field labels, rendered into the application's configuration as a JSON object
        // the shared i18n runtime prefers over the language catalogs (see countryLabelOverlay).
        parameters.put("countryLabels", JavaScriptJson.compact(countryLabelOverlay(model, parameters)));
        // The application's reports, as the intent generated them into the model (#8277): the shell's
        // reports store lists these instead of discovering them through the core repository API,
        // which a business user may not call. null - not an empty list - for a model that carries
        // none, so the store keeps discovering the reports a developer generated outside the intent.
        Object reports = model.get("reports");
        parameters.put("appReports", reports instanceof List ? JavaScriptJson.compact(reports) : "null");
        return new PreparedModel(model, true);
    }

    /**
     * The application's country label overlay: the property labels that are resolved from the tenant's
     * country instead of the reader's language, as <code>{ &lt;country&gt;: { &lt;translation key&gt;:
     * &lt;label&gt; } }</code>.
     *
     * <p>
     * Keyed by the very translation key the generated views bind - {@code <project>:<tprefix>.t.<data
     * name>} - so the runtime resolves an overlay with one exact lookup and needs to know nothing about
     * how a key is composed. The overlay deliberately does NOT travel in the language catalogs: those
     * are per language and are not even loaded in the default one, which is exactly the mismatch a
     * country-scoped label suffers from (dirigible #6424).
     *
     * @param model the entity model
     * @param parameters the generation parameters, for the project name and the catalog prefix
     * @return the overlay, empty when no field declares a country label
     */
    private static Map<String, Object> countryLabelOverlay(Map<String, Object> model, Map<String, Object> parameters) {
        String namespace = str(parameters, "projectName") + ":" + ModelTranslations.catalogPrefix(str(parameters, "filePath")) + ".t.";
        Map<String, Object> overlay = new LinkedHashMap<>();
        for (Map<String, Object> entity : asMaps(model.get("entities"))) {
            for (Map<String, Object> property : asMaps(entity.get("properties"))) {
                Map<String, Object> variants = asMap(property.get("widgetCountryLabels"));
                if (variants == null || str(property, "dataName") == null) {
                    continue;
                }
                for (Map.Entry<String, Object> variant : variants.entrySet()) {
                    @SuppressWarnings("unchecked")
                    Map<String, Object> labels =
                            (Map<String, Object>) overlay.computeIfAbsent(variant.getKey(), country -> new LinkedHashMap<String, Object>());
                    labels.put(namespace + str(property, "dataName"), variant.getValue());
                }
            }
        }
        return overlay;
    }

    /**
     * Prepares a glue file. It carries no entities, so it is given an empty list - the entity pipeline
     * partitions that list up front, and every glue source names a glue collection instead.
     *
     * @param modelText the raw model file
     * @param parameters the generation parameters
     * @return the prepared model
     */
    private static PreparedModel glue(String modelText, Map<String, Object> parameters) {
        Map<String, Object> model = ModelJson.parseObject(modelText);
        if (!(model.get("entities") instanceof List)) {
            model.put("entities", new ArrayList<>());
        }
        parameters.put("javaGenFolderName", NamingHelper.sanitizeJavaIdentifier(str(parameters, "genFolderName")));
        return new PreparedModel(model, true);
    }

    /**
     * A relative moment (#8506): {@code CURRENT_DATE} or {@code START_OF_YEAR/_QUARTER/_MONTH}, then
     * signed ISO-8601 date periods - the grammar of the intent's {@code ReportMoments}, which emits it
     * in this canonical spelling (upper case, no whitespace).
     */
    private static final java.util.regex.Pattern REPORT_MOMENT = java.util.regex.Pattern.compile(
            "(?:CURRENT_DATE|START_OF_(?:YEAR|QUARTER|MONTH))(?:[+-]P(?=\\d)(?:\\d{1,5}Y)?(?:\\d{1,5}M)?(?:\\d{1,5}W)?(?:\\d{1,5}D)?)*");

    /**
     * The canonical moment a DATE parameter's initial names, or null when it is a fixed value or the
     * bare {@code CURRENT_DATE} (which the repository template resolves on its own branch).
     */
    static String reportMoment(String type, String initial) {
        if (!"DATE".equalsIgnoreCase(type) || initial == null) {
            return null;
        }
        String moment = initial.replaceAll("\\s+", "")
                               .toUpperCase(java.util.Locale.ROOT);
        return !"CURRENT_DATE".equals(moment) && REPORT_MOMENT.matcher(moment)
                                                              .matches() ? moment : null;
    }

    /**
     * Prepares a standalone report, resolving its column and parameter types and pre-escaping its query
     * for the generated repository.
     *
     * @param modelText the raw model file
     * @param parameters the generation parameters
     * @return the prepared model
     */
    private static PreparedModel report(String modelText, Map<String, Object> parameters) {
        Map<String, Object> model = ModelJson.parseObject(modelText);
        // A column the query groups by but does not select (a relation dimension's key, #8102) is no
        // column of the report's rows - not to show, filter, total or export.
        if (model.get("columns") instanceof List<?> columns) {
            columns.removeIf(column -> column instanceof Map<?, ?> map && "false".equals(String.valueOf(map.get("select"))));
        }
        for (Map<String, Object> column : asMaps(model.get("columns"))) {
            ModelDataTypes.DataType dataType = ModelDataTypes.parse(str(column, "type"));
            column.put("typeJava", dataType.java());
            column.put("typeTypescript", dataType.typescript());
            if ("Date".equals(dataType.typescript())) {
                model.put("hasDates", Boolean.TRUE);
            }
            // Rendering defaults for reports authored before the column alignment and pattern
            // metadata: a numeric column right-aligns, a decimal one gets the platform money pattern.
            if (!truthy(column, "align")) {
                column.put("align", "number".equals(dataType.typescript()) ? "right" : "left");
            }
            String sqlType = strOr(column, "type", "").toUpperCase(java.util.Locale.ROOT);
            if (!truthy(column, "pattern") && ("DECIMAL".equals(sqlType) || "DOUBLE".equals(sqlType))) {
                column.put("pattern", "### ### ### ##0.00");
            }
        }
        for (Map<String, Object> parameter : asMaps(model.get("parameters"))) {
            ModelDataTypes.DataType dataType = ModelDataTypes.parse(str(parameter, "type"));
            parameter.put("typeJava", dataType.java());
            parameter.put("typeTypescript", dataType.typescript());
            // The authored fallback the parameter is bound with when the caller leaves the input empty.
            // The generated repository writes it into a Java string literal, so an apostrophe-carrying
            // value is fine but a quote or a backslash would end that literal and fail the compile of
            // the whole generated module (#7295).
            parameter.put("initialJavaLiteral", JavaLiterals.escape(strOr(parameter, "initial", "")));
            // A relative moment as a date parameter's initial (#8506) - START_OF_MONTH, CURRENT_DATE-P30D -
            // is resolved by the generated repository on every request. A bare CURRENT_DATE keeps its own
            // branch in the template.
            String initialMoment = reportMoment(str(parameter, "type"), strOr(parameter, "initial", ""));
            if (initialMoment != null) {
                parameter.put("initialMoment", initialMoment);
                model.put("hasMomentParameters", Boolean.TRUE);
            }
            String placeholder = ":" + str(parameter, "name");
            for (Map<String, Object> condition : asMaps(model.get("conditions"))) {
                if (placeholder.equals(str(condition, "right")) && "string".equals(dataType.typescript())
                        && "LIKE".equals(str(condition, "operation"))) {
                    parameter.put("isLikeCondition", Boolean.TRUE);
                }
            }
        }
        String query = strOr(model, "query", "");
        // The report's query pre-escaped as PER-LINE Java string literals, for the generated
        // repository to join back with newlines. Deliberately never one single-line literal: a
        // multi-kilobyte escaped-quote-dense literal is exactly what overflowed the platform's
        // literal-scanning source parser and took synchronization down instance-wide (#6936) - and
        // since the heavy report kinds keep their structural SQL in a generated .view (#6938), each
        // line here stays short by construction.
        List<Object> queryJavaLines = new ArrayList<>();
        for (String line : query.split("\n", -1)) {
            queryJavaLines.add(JavaScriptJson.compact(line));
        }
        model.put("queryJavaLines", queryJavaLines);
        model.put("orderByJavaLiteral", JavaLiterals.escape(outerOrderBy(model)));
        if (!parameters.containsKey("extensionPoint")) {
            parameters.put("extensionPoint", parameters.get("projectName"));
        }
        if (!parameters.containsKey("name")) {
            parameters.put("name", model.get("name"));
        }
        parameters.put("perspectiveName", "Reports");
        parameters.put("javaGenFolderName", NamingHelper.sanitizeJavaIdentifier(str(parameters, "genFolderName")));
        parameters.put("javaPerspectiveName", NamingHelper.sanitizeJavaIdentifier(str(parameters, "perspectiveName")));
        parameters.put("roles", reportRoles(model));
        return new PreparedModel(model, false);
    }

    /**
     * The report's row order re-spelt over its OUTPUT columns, for the generated repository to re-apply
     * when it wraps the query in the per-column filters ({@code SELECT * FROM (QUERY) AS "REPORT_DATA"
     * WHERE ...}): an ORDER BY inside a derived table does not order the rows the outer SELECT returns,
     * so a filtered page or dashboard tile would lose it (dirigible #8435). Only an ordering whose
     * every term is a quoted output alias can be re-spelt outside; any other (a hand-edited ordering by
     * a table column) leaves the outer query unordered, as before.
     *
     * @param model the parsed report model
     * @return the ORDER BY terms ({@code "Month" ASC, "Total" DESC}), or empty for none
     */
    private static String outerOrderBy(Map<String, Object> model) {
        Set<String> aliases = new HashSet<>();
        for (Map<String, Object> column : asMaps(model.get("columns"))) {
            aliases.add(strOr(column, "alias", ""));
        }
        List<String> terms = new ArrayList<>();
        for (Map<String, Object> ordering : asMaps(model.get("orderings"))) {
            String column = strOr(ordering, "column", "").trim();
            String direction = strOr(ordering, "direction", "ASC").trim()
                                                                  .toUpperCase(java.util.Locale.ROOT);
            if (column.length() < 3 || !column.startsWith("\"") || !column.endsWith("\"")
                    || !aliases.contains(column.substring(1, column.length() - 1))
                    || !("ASC".equals(direction) || "DESC".equals(direction))) {
                return "";
            }
            terms.add(column + " " + direction);
        }
        return String.join(", ", terms);
    }

    /**
     * Collects the default roles a report asks to be generated - each gate's own role, its first (see
     * {@link ModelValues#defaultRole}).
     *
     * @param model the report model
     * @return the roles
     */
    private static List<Object> reportRoles(Map<String, Object> model) {
        List<Object> roles = new ArrayList<>();
        Map<String, Object> security = asMap(model.get("security"));
        if (security == null || !"true".equals(security.get("generateDefaultRoles"))) {
            return roles;
        }
        Map<String, Object> rolePair = new LinkedHashMap<>();
        rolePair.put("entityName", model.get("name"));
        String roleRead = defaultRole(security, "roleRead");
        if (roleRead != null) {
            rolePair.put("roleRead", roleRead);
        }
        String roleWrite = defaultRole(security, "roleWrite");
        if (roleWrite != null) {
            rolePair.put("roleWrite", roleWrite);
        }
        roles.add(rolePair);
        return roles;
    }

    /**
     * Prepares a form. Its code is the body of the generated controller function, so it is indented for
     * embedding.
     *
     * @param modelText the raw model file
     * @return the prepared model
     */
    private static PreparedModel form(String modelText) {
        Map<String, Object> model = ModelJson.parseObject(modelText);
        String code = str(model, "code");
        if (code != null && !code.isEmpty()) {
            StringBuilder indented = new StringBuilder(code.length() + 32);
            String[] lines = code.split("\n", -1);
            for (int i = 0; i < lines.length; i++) {
                if (i > 0) {
                    indented.append('\n');
                }
                indented.append("    ")
                        .append(lines[i]);
            }
            model.put("code", indented.toString());
        }
        return new PreparedModel(model, false);
    }

    /**
     * Prepares a mapping. The template embeds the mapping file verbatim, so the raw text is handed
     * through rather than the parsed graph.
     *
     * @param modelText the raw model file
     * @return the prepared model
     */
    private static PreparedModel mapping(String modelText) {
        Map<String, Object> model = new LinkedHashMap<>();
        model.put("mapping", modelText);
        return new PreparedModel(model, false);
    }

    /**
     * Prepares a mapping for the client-Java mapper, whose sources render the compiled column
     * expressions rather than the mapping file.
     *
     * @param modelText the raw model file
     * @param parameters the generation parameters, mutated with the mapper's package and class name
     * @return the prepared model
     */
    private static PreparedModel javaMapping(String modelText, Map<String, Object> parameters) {
        parameters.put("javaGenFolderName", NamingHelper.sanitizeJavaIdentifier(str(parameters, "genFolderName")));
        parameters.put("mapperClassName", MappingCompiler.className(str(parameters, "fileName")));
        return new PreparedModel(MappingCompiler.compile(modelText), false);
    }

    /**
     * Reads the entity model out of a model file, which wraps it under a {@code model} key.
     *
     * @param modelText the raw model file
     * @return the entity model
     */
    private static Map<String, Object> entityRoot(String modelText) {
        Map<String, Object> root = ModelJson.parseObject(modelText);
        Map<String, Object> model = asMap(root.get("model"));
        return model == null ? new LinkedHashMap<>() : model;
    }

    /**
     * Normalizes a blank string to null, for the "prefer this if it says anything" checks.
     *
     * @param value the value
     * @return the trimmed value, or null when it is absent or blank
     */
    private static String blankToNull(String value) {
        return value == null || value.isBlank() ? null : value.trim();
    }

}
